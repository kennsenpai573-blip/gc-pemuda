-- Jalankan sekali di Supabase SQL Editor untuk mengaktifkan fitur Channel.
create table if not exists public.community_channels (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  platform text not null check (platform in ('whatsapp','website')),
  description text not null default '',
  image_url text,
  link_url text,
  announcement text not null default '',
  is_published boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint channel_link_check check (
    (platform = 'website' and (link_url is null or link_url = '')) or
    (platform = 'whatsapp' and (link_url is null or link_url = '' or link_url ~ '^https://whatsapp.com/channel/[A-Za-z0-9]+/?$' or link_url ~ '^https://www.whatsapp.com/channel/[A-Za-z0-9]+/?$'))
  )
);
alter table public.community_channels enable row level security;
drop policy if exists "Published channels are public" on public.community_channels;
create policy "Published channels are public" on public.community_channels for select using (is_published = true);
drop policy if exists "Staff manage channels" on public.community_channels;
create policy "Staff manage channels" on public.community_channels for all to authenticated
using (exists (select 1 from public.staff_profiles p where p.user_id = auth.uid() and p.role in ('owner','admin')))
with check (exists (select 1 from public.staff_profiles p where p.user_id = auth.uid() and p.role in ('owner','admin')));
create index if not exists community_channels_published_created_idx on public.community_channels (is_published, created_at desc);
