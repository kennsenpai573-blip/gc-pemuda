-- Jalankan sekali di Supabase SQL Editor.
-- Pesan dapat dibuat/dibaca oleh Owner dan Admin melalui sesi website; service_role hanya di server bot.
create table if not exists public.whatsapp_message_queue (
  id bigint generated by default as identity primary key,
  recipient text not null,
  recipient_type text not null default 'private' check (recipient_type in ('private','group','channel')),
  message text not null check (char_length(message) between 1 and 4000),
  status text not null default 'queued' check (status in ('queued','processing','sent','failed')),
  created_by uuid not null default auth.uid(),
  created_at timestamptz not null default now(),
  processed_at timestamptz,
  error text
);
create index if not exists whatsapp_message_queue_status_created_idx
  on public.whatsapp_message_queue(status, created_at);
alter table public.whatsapp_message_queue enable row level security;
drop policy if exists "Owner manage WhatsApp queue" on public.whatsapp_message_queue;
drop policy if exists "Staff manage WhatsApp queue" on public.whatsapp_message_queue;
create policy "Staff manage WhatsApp queue" on public.whatsapp_message_queue
  for all to authenticated
  using (exists (
    select 1 from public.staff_profiles sp
    where sp.user_id = auth.uid() and sp.role in ('owner', 'admin')
  ))
  with check (exists (
    select 1 from public.staff_profiles sp
    where sp.user_id = auth.uid() and sp.role in ('owner', 'admin')
  ));
revoke all on public.whatsapp_message_queue from anon;
grant select, insert, update, delete on public.whatsapp_message_queue to authenticated;
grant usage, select on sequence public.whatsapp_message_queue_id_seq to authenticated;
-- service_role digunakan hanya di Pterodactyl, bukan di browser.
grant all on public.whatsapp_message_queue to service_role;
grant usage, select on sequence public.whatsapp_message_queue_id_seq to service_role;

-- Upgrade existing installations safely: support private chats, groups, and channels.
alter table public.whatsapp_message_queue
  add column if not exists recipient_type text not null default 'private';
alter table public.whatsapp_message_queue
  drop constraint if exists whatsapp_message_queue_recipient_check;
alter table public.whatsapp_message_queue
  drop constraint if exists whatsapp_message_queue_recipient_type_check;
alter table public.whatsapp_message_queue
  add constraint whatsapp_message_queue_recipient_type_check
  check (recipient_type in ('private','group','channel'));
alter table public.whatsapp_message_queue
  drop constraint if exists whatsapp_message_queue_recipient_format_check;
alter table public.whatsapp_message_queue
  add constraint whatsapp_message_queue_recipient_format_check
  check (
    (recipient_type = 'private' and recipient ~ '^[1-9][0-9]{7,14}$')
    or (recipient_type = 'group' and recipient ~ '^(?:[0-9]{5,30}|[0-9]{5,30}-[0-9]{5,30})@g\.us$')
    or (recipient_type = 'channel' and recipient ~ '^[A-Za-z0-9._-]{5,100}@newsletter$')
  );
