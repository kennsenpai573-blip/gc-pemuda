-- Jalankan sekali di Supabase SQL Editor. Tidak mengubah view/tabel member yang sudah ada.
create table if not exists public.member_friendships (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references auth.users(id) on delete cascade,
  addressee_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint member_friendships_not_self check (requester_id <> addressee_id),
  constraint member_friendships_pair_unique unique (requester_id, addressee_id)
);
create index if not exists member_friendships_addressee_status_idx on public.member_friendships(addressee_id,status);
create index if not exists member_friendships_requester_status_idx on public.member_friendships(requester_id,status);
alter table public.member_friendships enable row level security;
drop policy if exists "Users can read their own friendship rows" on public.member_friendships;
create policy "Users can read their own friendship rows" on public.member_friendships for select to authenticated using (auth.uid() = requester_id or auth.uid() = addressee_id);
revoke all on public.member_friendships from anon, authenticated;
grant select on public.member_friendships to authenticated;

create or replace function public.member_friend_status(p_other uuid)
returns text language plpgsql security definer set search_path = public, auth as $$
declare me uuid := auth.uid(); s text; req uuid;
begin
 if me is null then return 'login_required'; end if;
 if p_other is null or p_other = me then return 'self'; end if;
 select status, requester_id into s, req from public.member_friendships
 where (requester_id=me and addressee_id=p_other) or (requester_id=p_other and addressee_id=me)
 limit 1;
 if not found then return 'none'; end if;
 if s='accepted' then return 'friends'; end if;
 if req=me then return 'sent'; else return 'received'; end if;
end; $$;

create or replace function public.member_send_friend_request(p_other uuid)
returns text language plpgsql security definer set search_path = public, auth as $$
declare me uuid := auth.uid(); s text;
begin
 if me is null then raise exception 'Silakan login terlebih dahulu'; end if;
 if p_other is null or p_other=me then raise exception 'Tidak bisa menambahkan akun sendiri'; end if;
 -- Hanya akun yang punya profil member terdaftar yang boleh berteman.
 if not exists (select 1 from public.staff_profiles p where p.user_id=me) then raise exception 'Daftar sebagai member terlebih dahulu'; end if;
 if not exists (select 1 from public.staff_profiles p where p.user_id=p_other) then raise exception 'Akun ini belum terdaftar sebagai member'; end if;
 select status into s from public.member_friendships where (requester_id=me and addressee_id=p_other) or (requester_id=p_other and addressee_id=me) limit 1;
 if s='accepted' then return 'friends'; end if;
 if exists(select 1 from public.member_friendships where requester_id=p_other and addressee_id=me and status='pending') then return public.member_respond_friend_request(p_other,true); end if;
 if exists(select 1 from public.member_friendships where requester_id=me and addressee_id=p_other and status='pending') then return 'sent'; end if;
 insert into public.member_friendships(requester_id,addressee_id,status) values(me,p_other,'pending');
 return 'sent';
end; $$;

create or replace function public.member_respond_friend_request(p_other uuid, p_accept boolean)
returns text language plpgsql security definer set search_path = public, auth as $$
declare me uuid := auth.uid();
begin
 if me is null then raise exception 'Silakan login terlebih dahulu'; end if;
 if p_accept then
   update public.member_friendships set status='accepted',updated_at=now() where requester_id=p_other and addressee_id=me and status='pending';
   if not found then raise exception 'Permintaan teman tidak ditemukan'; end if;
   return 'friends';
 else
   delete from public.member_friendships where requester_id=p_other and addressee_id=me and status='pending';
   if not found then raise exception 'Permintaan teman tidak ditemukan'; end if;
   return 'none';
 end if;
end; $$;

create or replace function public.member_remove_friend(p_other uuid)
returns text language plpgsql security definer set search_path = public, auth as $$
declare me uuid := auth.uid();
begin
 if me is null then raise exception 'Silakan login terlebih dahulu'; end if;
 delete from public.member_friendships where status='accepted' and ((requester_id=me and addressee_id=p_other) or (requester_id=p_other and addressee_id=me));
 return 'none';
end; $$;
revoke all on function public.member_friend_status(uuid) from public, anon;
revoke all on function public.member_send_friend_request(uuid) from public, anon;
revoke all on function public.member_respond_friend_request(uuid,boolean) from public, anon;
revoke all on function public.member_remove_friend(uuid) from public, anon;
grant execute on function public.member_friend_status(uuid) to authenticated;
grant execute on function public.member_send_friend_request(uuid) to authenticated;
grant execute on function public.member_respond_friend_request(uuid,boolean) to authenticated;
grant execute on function public.member_remove_friend(uuid) to authenticated;
