-- UP SW queue: run once in Supabase SQL Editor.
-- Keep the bucket private. The browser can manage files only as Owner; bot uses service role on server.
create table if not exists public.whatsapp_status_queue (
  id bigint generated by default as identity primary key,
  media_type text not null check (media_type in ('text','image','video')),
  caption text,
  media_path text,
  status text not null default 'queued' check (status in ('queued','processing','sent','failed')),
  created_by uuid not null default auth.uid(),
  created_at timestamptz not null default now(),
  processed_at timestamptz,
  error text,
  constraint whatsapp_status_media_valid check (
    (media_type = 'text' and media_path is null and caption is not null and char_length(caption) between 1 and 700)
    or (media_type in ('image','video') and media_path is not null and (caption is null or char_length(caption) <= 700))
  )
);
create index if not exists whatsapp_status_queue_status_created_idx
  on public.whatsapp_status_queue(status, created_at);
alter table public.whatsapp_status_queue enable row level security;
drop policy if exists "Owner manage WhatsApp status queue" on public.whatsapp_status_queue;
create policy "Owner manage WhatsApp status queue" on public.whatsapp_status_queue
  for all to authenticated using (public.is_owner()) with check (public.is_owner());
revoke all on public.whatsapp_status_queue from anon;
grant select, insert, update, delete on public.whatsapp_status_queue to authenticated;
grant all on public.whatsapp_status_queue to service_role;
grant usage, select on sequence public.whatsapp_status_queue_id_seq to service_role;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('whatsapp-status', 'whatsapp-status', false, 67108864,
  array['image/jpeg','image/png','image/webp','image/gif','video/mp4','video/3gpp','video/quicktime'])
on conflict (id) do update set public = false, file_size_limit = 67108864;
drop policy if exists "Owner upload WhatsApp status media" on storage.objects;
create policy "Owner upload WhatsApp status media" on storage.objects
for insert to authenticated with check (bucket_id = 'whatsapp-status' and public.is_owner());
drop policy if exists "Owner read WhatsApp status media" on storage.objects;
create policy "Owner read WhatsApp status media" on storage.objects
for select to authenticated using (bucket_id = 'whatsapp-status' and public.is_owner());
drop policy if exists "Owner delete WhatsApp status media" on storage.objects;
create policy "Owner delete WhatsApp status media" on storage.objects
for delete to authenticated using (bucket_id = 'whatsapp-status' and public.is_owner());
